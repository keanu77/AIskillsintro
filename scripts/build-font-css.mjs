#!/usr/bin/env node
// Inline the subset display font into a stylesheet so it arrives with the
// CSS. A separately loaded font swapped in after first paint, and the wider
// text became a late LCP candidate (bimodal LCP on Lighthouse runs).
// Regenerate after changing src/app/fonts/archivo-display.woff2.

import fs from "node:fs";
import path from "node:path";

const dir = path.resolve(import.meta.dirname, "../src/app/fonts");
const font = fs.readFileSync(path.join(dir, "archivo-display.woff2")).toString("base64");

const css = `/* Generated by scripts/build-font-css.mjs — do not edit by hand.
   Archivo (SIL OFL 1.1, see Archivo-OFL.txt), instanced to wght 800–900,
   wdth 100–125 and subset to Basic Latin + a few symbols. */
@font-face {
  font-family: "Archivo Display";
  src: url(data:font/woff2;base64,${font}) format("woff2");
  font-weight: 800 900;
  font-stretch: 100% 125%;
  font-display: block;
}
`;

fs.writeFileSync(path.join(dir, "archivo-display.css"), css);
console.log(`wrote archivo-display.css (${Math.round(css.length / 1024)} KB)`);
